"""Documentation checks over the Swift symbol graphs from an `xcodebuild docbuild` run.

Usage: docs_tool.py <repository-root> <symbol-graph-dir> <output-dir> <module>...

- Coverage: every public and internal symbol declared under Sources/ has its own DocC comment
  (AGENTS.md, "Complete API documentation"). Inherited comments don't count.
- Export: writes one Markdown file per module to <output-dir> (docs/api/ in the repository), so
  agents can read the API without building (AGENTS.md, "Agent-readable output").
"""
import glob
import json
import os
import sys

root, graph_dir, output_dir, modules = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
sources = os.path.realpath(os.path.join(root, "Sources")) + os.sep
undocumented = []


def local_path(uri):
    """Returns the repository-relative path of a file:// URI inside Sources/, or None."""
    path = os.path.realpath(uri.removeprefix("file://"))
    return os.path.relpath(path, os.path.realpath(root)) if path.startswith(sources) else None


for module in modules:
    symbols = {}
    for graph in sorted(glob.glob(os.path.join(graph_dir, f"{module}.symbols.json"))
                        + glob.glob(os.path.join(graph_dir, f"{module}@*.symbols.json"))):
        with open(graph, encoding="utf-8") as handle:
            for symbol in json.load(handle)["symbols"]:
                uri = symbol.get("location", {}).get("uri", "")
                path = local_path(uri) if uri else None
                if path is None or symbol["kind"]["identifier"] == "swift.extension":
                    continue
                comment = symbol.get("docComment")
                own = comment is not None and comment.get("uri", uri) == uri
                name = "/".join(symbol["pathComponents"])
                if not own or not any(line["text"].strip() for line in comment["lines"]):
                    undocumented.append(f"{path}: {name}")
                    continue
                declaration = "".join(f["spelling"] for f in symbol.get("declarationFragments", []))
                doc = "\n".join(line["text"] for line in comment["lines"]).strip()
                symbols[(name, declaration)] = (path, declaration, doc, symbol["accessLevel"])

    lines = [f"# {module} API", "",
             "Generated by `scripts/check-docs.sh` from the DocC comments in `Sources/"
             f"{module}`. Do not edit by hand.", ""]
    for (name, _), (path, declaration, doc, access) in sorted(symbols.items()):
        lines += [f"## `{name}`", "", f"{access}, declared in `{path}`", "",
                  "```swift", declaration, "```", "", doc, ""]
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, f"{module}.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")
    print(f"{module}: {len(symbols)} documented symbols")

if undocumented:
    print("\n".join(f"docs: missing DocC comment: {item}" for item in undocumented))
    sys.exit(1)
print("documentation coverage: 100% of public and internal symbols")
