#!/usr/bin/env bash
# License review of every Rust crate compiled into the network-free C2PA library.
# Usage: scripts/check-c2pa-lib-licenses.sh <work-dir> [--write]
#   <work-dir>  the folder scripts/build-c2pa-lib.sh used (it holds the prepared c2pa-rs checkout).
# 1. cargo-deny: every crate's license is in c2pa-lib/deny.toml's allow list (GPL-3.0-only
#    compatible), and no network crate is in the graph.
# 2. c2pa-lib/CRATES.md lists every compiled crate with its version and license; the check fails
#    if it is out of date. Pass --write to update it.
# Needs cargo and cargo-deny on PATH.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
work="${1:?usage: check-c2pa-lib-licenses.sh <work-dir> [--write]}"
mode="${2:-check}"
src="$(cd "$work/c2pa-rs" && pwd)"
# shellcheck source=../c2pa-lib/versions.env
. "$here/c2pa-lib/versions.env"

cd "$src"
cargo deny --manifest-path c2pa_c_ffi/Cargo.toml --config "$here/c2pa-lib/deny.toml" \
  check licenses bans

# The crates compiled into the library: normal dependencies for each Apple target, with the
# build's features (build scripts and proc macros run on the build machine and aren't linked).
list=$(mktemp)
for target in $C2PA_TARGETS; do
  cargo tree --locked -p c2pa-c-ffi --target "$target" --no-default-features \
    --features "$C2PA_FEATURES" -e normal --prefix none --format '{p}' | sed 's/ (\*)$//; s/ (proc-macro)$//'
done | sort -u >"$list"
table=$(cargo metadata --locked --format-version 1 | python3 -I -c '
import json, sys
wanted = set(" ".join(line.split()[:2]) for line in open(sys.argv[1]) if line.strip())
meta = json.load(sys.stdin)
rows = []
for p in meta["packages"]:
    key = p["name"] + " v" + p["version"]
    if key in wanted:
        rows.append((p["name"], p["version"], p.get("license") or "(see " + str(p.get("license_file")) + ")",
                     p.get("repository") or ""))
for name, version, lic, repo in sorted(rows):
    print(f"| {name} | {version} | {lic} | {repo} |")
' "$list")
rm -f "$list"

out="$here/c2pa-lib/CRATES.md"
new=$(mktemp)
{
  echo "# Rust crates in the C2PA library"
  echo
  echo "Every Rust crate compiled into \`C2PAC.xcframework\` (c2pa-rs $C2PA_RS_TAG, features"
  echo "\`$C2PA_FEATURES\`, targets $C2PA_TARGETS), with its license as published on crates.io."
  echo "Generated by \`scripts/check-c2pa-lib-licenses.sh\`; every license is checked against"
  echo "\`c2pa-lib/deny.toml\`. Build-time tools (build scripts, procedural macros, cbindgen) aren't linked"
  echo "into the library and aren't listed."
  echo
  echo "| Crate | Version | License | Source |"
  echo "|---|---|---|---|"
  echo "$table"
} >"$new"

if [[ "$mode" == "--write" ]]; then
  mv "$new" "$out"; echo "updated $out"
elif ! diff -u "$out" "$new"; then
  rm -f "$new"; echo "c2pa-lib: CRATES.md is out of date; run scripts/check-c2pa-lib-licenses.sh <work-dir> --write"; exit 1
else
  rm -f "$new"; echo "c2pa-lib: licenses ok; CRATES.md matches"
fi
